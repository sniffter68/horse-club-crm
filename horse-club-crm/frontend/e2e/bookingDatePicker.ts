import { expect, type Locator, type Page } from './fixtures'

export async function checkBookingDatePicker(page: Page, owner: Locator, label: string, now: string) {
  const input = owner.getByLabel(label, { exact: true })
  await input.click()
  const popup = page.locator('.booking-date-popup:visible')
  const ok = popup.getByRole('button', { name: 'ОК', exact: true })
  await expect(ok).toBeVisible()
  await expect(ok).toBeInViewport({ ratio: 1 })
  await expect(popup.getByText('Сейчас', { exact: true })).toBeVisible()
  // Select a day, hour and minute through the actual calendar controls.
  await popup.locator('.ant-picker-cell-in-view').filter({ hasText: /^15$/ }).click()
  await expect(popup.locator('.ant-picker-cell-selected')).toHaveText('15')
  await popup.locator('.ant-picker-time-panel-column').nth(0).getByText('14', { exact: true }).click()
  await expect(popup.locator('.ant-picker-time-panel-column').nth(0).locator('.ant-picker-time-panel-cell-selected')).toHaveText('14')
  await popup.locator('.ant-picker-time-panel-column').nth(1).getByText('25', { exact: true }).click()
  await expect(popup.locator('.ant-picker-time-panel-column').nth(1).locator('.ant-picker-time-panel-cell-selected')).toHaveText('25')
  await ok.click()
  await expect(popup).toHaveCount(0)
  const selected = await input.inputValue()
  expect(selected).toMatch(/^15\.\d{2}\.\d{4} 14:25$/)
  await expect(owner).toBeVisible()
  await input.click()
  await input.press('Escape')
  await expect(popup).toHaveCount(0)
  await expect(input).toHaveValue(selected)
  await expect(owner).toBeVisible()
  await input.click()
  await popup.getByText('Сейчас', { exact: true }).click()
  await expect(input).toHaveValue(now)
  await expect(popup).toHaveCount(0)
  await input.click()
  await expect(ok).toBeVisible()
  await expect(ok).toBeInViewport({ ratio: 1 })
  await expect(popup).toHaveCSS('opacity', '1')
  await page.screenshot({ path: `test-results/booking-picker-${label.replace(/[^а-яА-Яa-z]/g, '')}-${page.viewportSize()?.width}.png`, animations: 'disabled' })
  await ok.click()
  await expect(popup).toHaveCount(0)
}
