import { test, expect, type Page } from '@playwright/test'
import { DateTime } from 'luxon'

async function login(page: Page, email: string) {
  await page.goto('/login')
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Пароль', { exact: true }).fill('staff-test-password')
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page).not.toHaveURL(/\/login/)
}

test('admin plans and completes a shift, adjusts payroll, pays CASH and sees salary expense and lower balance', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 950 })
  await login(page, 'staff-admin@test.local')
  await page.goto('/staff')
  await page.getByRole('button', { name: 'Запланировать смену', exact: true }).click()
  const shiftDialog = page.getByRole('dialog', { name: 'Запланировать смену', exact: true })
  await shiftDialog.getByRole('combobox', { name: 'Сотрудник', exact: true }).press('ArrowDown')
  await page.locator('.ant-select-dropdown:visible').getByText('Проверка выплаты', { exact: true }).click()
  await shiftDialog.getByRole('textbox', { name: 'Комментарий', exact: true }).fill('Контрольная смена')
  const created = page.waitForResponse(response => response.url().endsWith('/api/staff/shifts') && response.request().method() === 'POST')
  await shiftDialog.getByRole('button', { name: 'Запланировать смену', exact: true }).click()
  expect((await created).status()).toBe(201)
  await expect(shiftDialog).not.toBeVisible()
  const employee = page.locator('.staff-grid tbody tr').filter({ hasText: 'Проверка выплаты' })
  await expect(employee).toContainText('Запланирована')
  const refreshed = page.waitForResponse(async response => response.request().method() === 'GET' && response.url().includes('/api/staff/shifts?') && (await response.json()).data.some((row: { status: string }) => row.status === 'COMPLETED'))
  await employee.getByRole('button', { name: /^Отметить смену отработанной:/ }).click()
  await refreshed
  await expect(employee).toContainText('Отработана')
  await employee.getByRole('button', { name: /Отработана/ }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: 'test-results/staff-calendar-desktop.png', fullPage: true })
  await page.getByRole('tab', { name: 'Табель и расчет зарплаты', exact: true }).click()
  const payrollRow = page.locator('.ant-table-tbody tr').filter({ hasText: 'Проверка выплаты' })
  await expect(payrollRow).toContainText(/1\s*500,00/)
  await payrollRow.getByRole('button', { name: 'Премии / Штрафы', exact: true }).click()
  const adjustment = page.getByRole('dialog', { name: 'Начисления: Проверка выплаты', exact: true })
  await adjustment.getByRole('spinbutton', { name: 'Премии и надбавки (₽)', exact: true }).fill('100')
  await adjustment.getByRole('spinbutton', { name: 'Удержания и штрафы (₽)', exact: true }).fill('50')
  await adjustment.getByRole('button', { name: 'Сохранить расчет', exact: true }).click()
  await expect(adjustment).not.toBeVisible()
  await expect(payrollRow).toContainText(/1\s*550,00/)
  const now = DateTime.now().setZone('Europe/Moscow').toISODate()!
  const before = await page.request.get(`/api/finance/summary?from=${now}&to=${now}&page=1&pageSize=20`)
  expect(before.ok()).toBeTruthy()
  const balanceBefore = Number((await before.json()).balanceCash)
  await payrollRow.getByRole('button', { name: 'Выплатить', exact: true }).click()
  const payout = page.getByRole('dialog', { name: 'Выплатить зарплату', exact: true })
  await expect(payout).toContainText(/1\s*550,00/)
  await payout.getByRole('combobox', { name: 'Способ выплаты', exact: true }).press('ArrowDown')
  await expect(page.locator('.ant-select-dropdown:visible')).toContainText('С расчетного счета (Безнал)')
  await page.keyboard.press('Escape')
  // Failed/uncertain response keeps the modal and operation ID available for retry.
  await page.route('**/api/payroll/payout', async route => {
    const response = await route.fetch()
    expect(response.ok()).toBeTruthy()
    await route.fulfill({ status: 503, json: { message: 'Ответ о выплате потерян. Повторите запрос.' } })
    await page.unroute('**/api/payroll/payout')
  }, { times: 1 })
  await payout.getByRole('button', { name: 'Выплатить зарплату', exact: true }).click()
  await expect(payout).toContainText('Ответ о выплате потерян')
  await payout.getByRole('button', { name: 'Выплатить зарплату', exact: true }).click()
  await expect(payout).not.toBeVisible()
  await expect(payrollRow).toContainText('Выплачено')
  await expect(payrollRow.getByRole('button', { name: 'Выплатить', exact: true })).toHaveCount(0)
  await page.goto('/cash-desk')
  const balance = page.locator('.kpi-card').filter({ hasText: 'Остаток в кассе (наличные)' })
  const expected = new Intl.NumberFormat('ru-RU', { minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(balanceBefore - 1550)
  await expect(balance).toContainText(expected)
  await expect(page.getByText(/Выплата зарплаты: Проверка выплаты/)).toBeVisible()
  await page.reload()
  await expect(balance).toContainText(expected)
  const expenses = await page.request.get(`/api/finance/expenses?from=${now}&to=${now}&category=SALARY`)
  expect((await expenses.json()).data.filter((row: { description: string }) => row.description.includes('Проверка выплаты'))).toHaveLength(1)
  await page.screenshot({ path: 'test-results/staff-salary-cash-desk.png', fullPage: true })
})

test('rates use the shared form: validation, create, edit, retry, narrow layout and dark theme', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await login(page, 'staff-admin@test.local')
  const email = `staff-${Date.now()}@test.local`
  const createdUser = await page.request.post('/api/users', { headers: { Origin: new URL(page.url()).origin }, data: { email, password: 'staff-test-password', role: 'TRAINER' } })
  expect(createdUser.ok(), await createdUser.text()).toBeTruthy()
  await page.goto('/staff?tab=rates')
  await page.getByRole('button', { name: 'Добавить сотрудника', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Добавить сотрудника', exact: true })
  await dialog.getByRole('button', { name: 'Сохранить ставки', exact: true }).click()
  await expect(dialog.getByText('Заполните поле')).toHaveCount(3)
  await dialog.getByRole('combobox', { name: 'Учетная запись', exact: true }).fill(email)
  await dialog.getByRole('combobox', { name: 'Учетная запись', exact: true }).press('ArrowDown')
  await page.locator('.ant-select-dropdown:visible').getByText(email, { exact: true }).click()
  await dialog.getByRole('textbox', { name: 'ФИО', exact: true }).fill('Сотрудник формы')
  await dialog.getByRole('textbox', { name: 'Должность', exact: true }).fill('Конюх')
  await dialog.getByRole('spinbutton', { name: 'Ставка за смену (₽)', exact: true }).fill('2200.50')
  await page.route('**/api/staff', route => route.fulfill({ status: 503, json: { message: 'Временная ошибка сохранения' } }), { times: 1 })
  await dialog.getByRole('button', { name: 'Сохранить ставки', exact: true }).click()
  await expect(dialog).toContainText('Временная ошибка сохранения')
  await expect(dialog.getByRole('textbox', { name: 'ФИО', exact: true })).toHaveValue('Сотрудник формы')
  await expect(dialog.locator('.ant-btn-loading')).toHaveCount(0)
  await dialog.getByRole('button', { name: /Сохранить ставки/ }).click()
  await expect(dialog).not.toBeVisible()
  const card = page.locator('.responsive-record-item').filter({ hasText: 'Сотрудник формы' })
  await expect(card).toContainText(/2\s*200,50/)
  await card.getByRole('button', { name: 'Изменить ставки', exact: true }).click()
  const edit = page.getByRole('dialog', { name: 'Ставки: Сотрудник формы', exact: true })
  await edit.getByRole('spinbutton', { name: 'Ставка за смену (₽)', exact: true }).fill('3000')
  await edit.getByRole('button', { name: 'Сохранить ставки', exact: true }).click()
  await expect(edit).not.toBeVisible()
  await expect(card).toContainText(/3\s*000,00/)
  await page.evaluate(() => localStorage.setItem('horsecrm.color_mode', 'dark'))
  await page.reload()
  await expect(card).toContainText(/3\s*000,00/)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: 'test-results/staff-rates-mobile-dark.png', fullPage: true })
})

test('trainer sees only own schedule and payroll on mobile, no management controls, foreign requests get 403', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await login(page, 'staff-trainer@test.local')
  await page.goto('/staff')
  await expect(page.getByText('В этом месяце смен нет')).toBeVisible()
  await expect(page.getByRole('tab', { name: 'Настройки ставок', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Запланировать смену', exact: true })).toHaveCount(0)
  await page.getByRole('tab', { name: 'Табель и расчет зарплаты', exact: true }).click()
  await expect(page.getByText('Личный график', { exact: true })).toBeVisible()
  await expect(page.getByText('Проверка выплаты', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Выплатить', exact: true })).toHaveCount(0)
  const response = await page.request.get('/api/payroll/calculate?from=2026-10-01&to=2026-10-31&staffId=11111111-1111-4111-8111-111111111111')
  expect(response.status()).toBe(403)
  expect((await page.request.post('/api/payroll/payout', { headers: { Origin: new URL(page.url()).origin }, data: {} })).status()).toBe(403)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: 'test-results/staff-trainer-mobile.png', fullPage: true })
})
