import { test, expect } from './fixtures'

for (const width of [390, 1440]) test(`unified trainer form saves all fields once at ${width}px`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 900 })
  await page.addInitScript(() => {
    localStorage.setItem('horsecrm.access_token', 'cookie-session')
    localStorage.setItem('horsecrm.role', 'ADMIN')
    localStorage.setItem('horsecrm.email', 'qa@example.com')
  })
  await page.route('**/api/staff?*', route => route.fulfill({ json: { data: [], total: 0 } }))
  await page.route('**/api/staff/candidates', route => route.fulfill({ json: [] }))
  await page.route('**/api/trainers?*', route => route.fulfill({ json: [], headers: { 'x-total-count': '0' } }))
  const requests: Record<string, unknown>[] = []
  await page.route('**/api/staff', route => {
    requests.push(route.request().postDataJSON() as Record<string, unknown>)
    return route.fulfill({ status: 201, json: { id: '11111111-1111-4111-8111-111111111111' } })
  })
  await page.goto('/trainers')
  await expect(page).toHaveURL(/\/staff\?role=TRAINER$/)
  await expect(page.getByRole('button', { name: 'Тренеры', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: '+ Добавить сотрудника', exact: true }).click()
  const drawer = page.getByRole('dialog', { name: 'Добавить сотрудника', exact: true })
  await expect(drawer.getByRole('heading', { name: 'Направления и витрина', exact: true })).toHaveCount(0)
  await drawer.getByRole('textbox', { name: 'ФИО', exact: true }).fill('Анна Иванова')
  await drawer.getByRole('combobox', { name: 'Роль', exact: true }).focus()
  await page.keyboard.press('ArrowDown')
  await page.locator('.ant-select-dropdown:visible').getByText('Тренер', { exact: true }).click()
  await expect(drawer.getByRole('heading', { name: 'Ставка и зарплата', exact: true })).toBeVisible()
  await drawer.getByRole('switch', { name: 'Доступ в CRM', exact: true }).click()
  await drawer.getByRole('textbox', { name: 'Email', exact: true }).fill('anna@example.com')
  await drawer.getByLabel('Временный пароль', { exact: true }).fill('temporary-123')
  await drawer.getByRole('textbox', { name: 'VK ID или ссылка на страницу', exact: true }).fill('12345')
  await drawer.getByRole('switch', { name: 'Групповые занятия', exact: true }).click()
  await drawer.getByRole('switch', { name: 'Показывать на сайте и в записи ВК', exact: true }).click()
  await drawer.getByRole('textbox', { name: 'Короткое описание', exact: true }).fill('Тренер по выездке')
  await drawer.getByRole('textbox', { name: 'Фото (ссылка)', exact: true }).fill('https://example.com/anna.jpg')
  await drawer.getByRole('combobox', { name: 'Схема расчёта', exact: true }).focus()
  await page.keyboard.press('ArrowDown')
  await expect(page.locator('.ant-select-dropdown:visible').getByText('Фикс за занятие', { exact: true })).toBeVisible()
  await page.screenshot({ path: info.outputPath(`unified-staff-select-${width}.png`), animations: 'disabled' })
  await page.locator('.ant-select-dropdown:visible').getByText('Фикс за занятие', { exact: true }).click()
  await drawer.getByRole('spinbutton', { name: 'Ставка за занятие (₽)', exact: true }).fill('850')
  await expect(page.locator('.ant-select-dropdown:visible')).toHaveCount(0)
  await page.screenshot({ path: info.outputPath(`unified-staff-${width}.png`), animations: 'disabled' })
  expect(await drawer.evaluate(el => el.scrollWidth - el.clientWidth)).toBeLessThanOrEqual(1)
  await drawer.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await expect(drawer).toBeHidden()
  expect(requests).toHaveLength(1)
  expect(requests[0]).toMatchObject({ fullName: 'Анна Иванова', role: 'TRAINER', createCrmAccess: true,
    email: 'anna@example.com', temporaryPassword: 'temporary-123', vkId: '12345', allowGroup: false,
    isPublic: true, description: 'Тренер по выездке', imageUrl: 'https://example.com/anna.jpg', payScheme: 'FIXED', fixedPay: 850 })
})
