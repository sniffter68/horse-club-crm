const value = (name: keyof ImportMetaEnv): string => String(import.meta.env[name] ?? '').trim()
const escape = (text: string): string => text.replace(/[&<>"']/g, character => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[character]!)

export const legal = {
  operatorName: value('VITE_LEGAL_OPERATOR_NAME'),
  operatorAddress: value('VITE_LEGAL_OPERATOR_ADDRESS'),
  registration: value('VITE_LEGAL_OPERATOR_REGISTRATION'),
  privacyEmail: value('VITE_LEGAL_PRIVACY_EMAIL'),
  siteUrl: value('VITE_LEGAL_SITE_URL'),
  dataLocation: value('VITE_LEGAL_DATA_LOCATION'),
  consentVersion: value('VITE_LEGAL_CONSENT_VERSION') || '2026-09-19',
  effectiveDate: value('VITE_LEGAL_EFFECTIVE_DATE') || '19 сентября 2026 года',
}

const required: Array<[keyof typeof legal, string]> = [
  ['operatorName', 'наименование оператора'],
  ['operatorAddress', 'адрес оператора'],
  ['registration', 'ИНН и ОГРН/ОГРНИП'],
  ['privacyEmail', 'email по вопросам персональных данных'],
  ['siteUrl', 'адрес сайта'],
  ['dataLocation', 'место нахождения базы данных'],
]

export const missingLegalFields = required.filter(([key]) => !legal[key]).map(([, label]) => label)
if (legal.dataLocation && !/росси/i.test(legal.dataLocation)) missingLegalFields.push('база первичного сбора должна находиться в Российской Федерации')
export const legalReady = missingLegalFields.length === 0

const operator = () => `<strong>${escape(legal.operatorName)}</strong><br>${escape(legal.registration)}<br>${escape(legal.operatorAddress)}`

